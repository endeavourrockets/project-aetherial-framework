/*
 * bxcan.h --> small driver for the STM32F4 bxCAN controller
 * classic CAN only --> up to 8 data bytes per frame, 11 bit standard ids
 *
 * a CAN frame is just an id + a length 0..8 (DLC) + up to 8 data bytes.
 * the id is also the priority --> lower number wins when two boards talk
 * at the same time. there are no addresses, every board sees every frame
 * and its filters decide what to keep
 */
#ifndef BXCAN_H
#define BXCAN_H

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    uint16_t id; /* 11 bit, 0x000..0x7FF */
    uint8_t dlc; /* 0..8 */
    uint8_t data[8];
} can_frame_t;

/* base is CAN1_BASE or CAN2_BASE */
bool bxcan_init(uint32_t base, uint32_t bitrate);

/* filter banks 0..(can2_start-1) belong to CAN1, the rest to CAN2 */
void bxcan_filters_begin(unsigned can2_start_bank);
/* accept frames whose id matches 'id' in every bit set in 'mask' */
void bxcan_filter_mask(unsigned bank, uint16_t id, uint16_t mask, unsigned fifo);
/* accept exactly two ids */
void bxcan_filter_list(unsigned bank, uint16_t id1, uint16_t id2, unsigned fifo);
void bxcan_filters_end(void);

/* false --> all 3 transmit mailboxes are busy */
bool bxcan_send(uint32_t base, const can_frame_t *f);
/* takes the oldest frame from receive FIFO 0 or 1, false if it's empty */
bool bxcan_receive(uint32_t base, unsigned fifo, can_frame_t *f);

#endif

